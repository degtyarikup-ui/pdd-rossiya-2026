export function incidentGuide(event) {
  const operation = String(event.operation ?? '');
  const code = String(event.code ?? '');
  const [baseCode, ...rest] = code.split(':');
  const detail = rest.join(':');
  let level = 'high';
  if (operation === 'auth.recovered') level = 'info';
  else if (CRITICAL_OPERATIONS.has(operation)) level = 'critical';
  else if (event.category === 'infrastructure' && /^cron\.game_week$/.test(operation)) level = 'high';
  else if (LOW_OPERATIONS.test(operation)) level = 'low';
  else if (event.category === 'app' && !/^(flutter|dart)\./.test(operation) && !/^(startup\.(premium|auth)|auth\.dialog)$/.test(operation)) level = 'low';
  // Нехватка настройки на сервере блокирует всех — это срочно независимо от операции.
  if (['session_secret_not_configured', 'store_verification_not_configured'].includes(baseCode)) level = 'critical';

  const steps = [];
  const what = [];
  if (baseCode === 'credential_rejected' && detail) {
    const hit = CREDENTIAL_DETAILS.find(([re]) => re.test(detail));
    if (hit) {
      const status = detail.match(/_(\d+)$/)?.[1] ?? '';
      what.push(hit[1].replace('$1', status));
      steps.push(hit[2].replace('$1', status));
    }
  }
  const tries = detail.match(/^(\d+)x$/)?.[1];
  if (tries && ['timeout', 'network', 'network_error'].includes(baseCode)) {
    what.push('Попыток входа: ' + tries + ' (основной и запасной адрес) — ни одна не прошла.');
  } else if (tries && ['retry_ok', 'fallback_ok'].includes(baseCode)) {
    what.push('Попыток до успеха: ' + tries + '.');
  }
  if (baseCode === 'sign_in_failed' && /^\d+$/.test(detail)) {
    const known = GOOGLE_SIGN_IN[Number(detail)];
    if (known) { what.push(known[0]); steps.push(known[1]); }
  }
  if (!steps.length) {
    const byCode = Object.hasOwn(GUIDE_BY_CODE, baseCode) ? GUIDE_BY_CODE[baseCode] : null;
    const byOperation = Object.hasOwn(GUIDE_BY_OPERATION, operation) ? GUIDE_BY_OPERATION[operation] : null;
    if (byCode) steps.push(...byCode);
    else if (/^storekit2?_/.test(baseCode)) steps.push(...STOREKIT_STEPS);
    else if (byOperation) steps.push(...byOperation);
  }
  const [emoji, label, meaning] = LEVELS[level];
  return { level, emoji, label, meaning, what: what[0] || null, steps: steps.slice(0, 3) };
}
