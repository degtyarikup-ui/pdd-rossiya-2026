#!/usr/bin/env python3
"""Export trusted answers and image references for Telegram question reports.

Run after editing ticket content; --check detects a stale Worker catalogue.
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / 'server/install-notifier/report_questions_data.js'


def render():
    rows = []
    for category in ('ab', 'cd'):
        source = ROOT / f'assets/countries/ru/questions/questions_{category}.json'
        for ticket in json.loads(source.read_text())['tickets']:
            for number, question in enumerate(ticket['questions'], 1):
                answers = [f"{i}. {a['text']}" for i, a in enumerate(question['answers'], 1) if a['correct']]
                assert answers, (category, ticket['number'], number)
                image = question.get('image')
                if image:
                    assert (ROOT / f'assets/countries/ru/images/questions_{category}/{image}.webp').is_file()
                rows.append([category, ticket['number'], number, question['id'], question.get('variantId'), image, '\n'.join(answers)])
    return ('// Generated by tools/ru_content/export_report_questions.py; do not edit.\n'
            '// [category, ticket, number, id, variantId, image, correctAnswer]\n'
            'export const reportQuestions = [\n' + ',\n'.join(
                json.dumps(row, ensure_ascii=False, separators=(',', ':')) for row in rows) + '\n];\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    result = render()
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != result:
            raise SystemExit('Report catalogue is stale: run python3 tools/ru_content/export_report_questions.py')
    else:
        TARGET.write_text(result)
