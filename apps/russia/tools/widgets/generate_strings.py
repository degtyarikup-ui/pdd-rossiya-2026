"""Generate native widget gallery/fallback strings from the app's ARB sources."""
import json
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[2]
KEYS = {
    'homeWidgetName': 'streak_widget_name',
    'homeWidgetDescription': 'streak_widget_description',
    'homeWidgetCurrent': 'currentLabel',
    'homeWidgetBest': 'bestLabel',
    'homeWidgetDone': 'doneLabel',
    'homeWidgetContinue': 'continueLabel',
    'homeWidgetStart': 'startLabel',
    'homeWidgetFlameName': 'streak_widget_flame_name',
    'homeWidgetFlameDescription': 'streak_widget_flame_description',
    'homeWidgetMinimalName': 'streak_widget_minimal_name',
    'homeWidgetMinimalDescription': 'streak_widget_minimal_description',
    'homeWidgetRecordName': 'streak_widget_record_name',
    'homeWidgetRecordDescription': 'streak_widget_record_description',

}
for language in ('ru', 'en', 'kk'):
    data = json.loads((ROOT / f'lib/l10n/app_{language}.arb').read_text())
    directory = 'values' if language == 'ru' else f'values-{language}'
    android = ROOT / f'android/app/src/main/res/{directory}/streak_widget_strings.xml'
    android.parent.mkdir(parents=True, exist_ok=True)
    android.write_text('<!-- Generated by tools/widgets/generate_strings.py -->\n<resources>\n' +
        ''.join(f'    <string name="{name}">{escape(data[key])}</string>\n' for key, name in KEYS.items()) + '</resources>\n')
    ios = ROOT / f'ios/StreakWidget/{language}.lproj/Localizable.strings'
    ios.parent.mkdir(parents=True, exist_ok=True)
    ios.write_text('// Generated by tools/widgets/generate_strings.py\n' +
        ''.join(f'"{name}" = {json.dumps(data[key], ensure_ascii=False)};\n' for key, name in KEYS.items()))
