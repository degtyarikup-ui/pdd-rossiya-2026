// Approach offsets move generated islands/paint, without moving the road or opposite end.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const L = require('../editor/layout.js');
const clone = s => JSON.parse(JSON.stringify(s));
const fixtures = [];
const near = (a,b) => assert.ok(Math.abs(a-b)<.001, `${a} != ${b}`);
for (const zebra of [false, true]) {
  const s = {schema:1,id:'median-offset-test',crop:90,layout:L.template('median',90),question:{maneuver:'straight',correct:0,text:{ru:{options:['Да']}}},roads:[],markings:[],lawns:[],routes:[],actors:[],lights:[]};
  const st = s.layout.streets.find(st => st.id === 's1');
  st.ends.b = {...st.ends.b, zebra};
  L.apply(s);
  const original = clone(s), base = L.playerPlan(s);
  const road = () => s.roads.find(r => r.id === 'road_s1');
  const front = () => Math.max(...road().holes[0].map(p => p[1]));
  const back = () => Math.min(...road().holes[0].map(p => p[1]));
  const nose = front(), border = back(), outline = clone(road().outer);
  const paint = type => s.markings.find(m => m.street === 's1' && m.type === type);
  const stopZ = paint('stop').points[0][1];
  const zebraZ = zebra ? paint('zebra').points[0][1] : null;
  s.layout.player = {...s.layout.player,street:st.id,toward:'c',questionAt:base.sd + 8};
  L.apply(s);
  L.setEndOffset(s,st.id,'c',-3);L.apply(s);
  near(front(), nose+3);
  assert.equal(back(),border,'border end stays fixed');
  assert.deepEqual(road().outer,outline,'street outline stays fixed');
  near(paint('stop').points[0][1],stopZ+3);
  if(zebra) near(paint('zebra').points[0][1],zebraZ+3);
  near(L.playerPlan(s).sd,base.sd+5);
  assert.deepEqual(s.roads.find(r=>r.id==='road_s2'),original.roads.find(r=>r.id==='road_s2'),'opposite arm unchanged');
  const saved=clone(s);L.apply(saved);assert.deepEqual(saved,s,'save/reload remains stable');
  fixtures.push({original, shifted:clone(s)});
  L.setEndOffset(s,st.id,'c',-100);L.apply(s);
  assert.equal(L.endOffset(s.layout,st,'c',90),-5,'cannot extend into cross traffic');
  L.setEndOffset(s,st.id,'c',1000);L.apply(s);
  assert.equal(L.endOffset(s.layout,st,'c',90),L.endOffsetLimits(s.layout,st,'c',90).max);
  assert.ok(road().holes[0].length >= 4 && front()-back()>4,'farther limit retains a visible island');
  L.setEndOffset(s,st.id,'c',0);L.apply(s);
  assert.deepEqual(clone(s.roads),original.roads,'reset restores islands');
  assert.deepEqual(s.markings,original.markings,'reset restores paint');
  L.setPlayerMode(s,'free');L.apply(s);const pose=clone(s.stop);
  L.setEndOffset(s,st.id,'c',-3);L.apply(s);assert.deepEqual(s.stop,pose,'free player remains where authored');
  L.setEndOffset(s,'s2','c',-3);L.apply(s);
  const north=s.roads.find(r=>r.id==='road_s2').holes[0];
  const oldNorth=original.roads.find(r=>r.id==='road_s2').holes[0];
  assert.equal(Math.min(...north.map(p=>p[1])),Math.min(...oldNorth.map(p=>p[1]))-3,'works at the other street end');
}
if(process.argv[2]) fs.writeFileSync(process.argv[2],JSON.stringify(fixtures));
console.log('Median position: island/stop/zebra/border/player/limits/reset/save-load PASS');
