#!/usr/bin/env python3
"""Build assets/game/i18n-situations.js: kk and en texts of the 3D game's exam situations.

Every situation in the game is a copy of an exam question (ticket T, question Q), so its
title, options, explanation and rule come verbatim from questions_ab_<lang>.json. This script
checks that the Russian copy in the game equals the Russian question, then writes the
translations keyed by the situation id. The game reads them by language at runtime
(assets/game/i18n.js); the Russian text stays in the game files as the source.
"""
import json, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parents[2]
QUESTIONS = ROOT / 'assets/countries/ru/questions'
GAME = ROOT / 'assets/game'
LANGS = ('kk', 'en')

def load(lang):
    name = 'questions_ab.json' if lang == 'ru' else f'questions_ab_{lang}.json'
    return json.loads((QUESTIONS / name).read_text(encoding='utf-8'))

questions = {lang: load(lang) for lang in ('ru',) + LANGS}

def question(lang, t, q):
    return questions[lang]['tickets'][t - 1]['questions'][q - 1]

def rule_number(comment):
    m = re.search(r'[Пп]ункт[ыа]?\s*([\d.]+)', comment or '')
    return m.group(1).rstrip('.') if m else None

def ru_rule(comment):
    n = rule_number(comment)
    return f'п. {n}' if n else ''

RULE_TEXT = {
    'kk': lambda n: f'ЖЖЕ {n}-тармағы',
    'en': lambda n: f'Clause {n}',
}

# (file, pattern) pairs that name the situations this build covers.
SOURCES = {
    'game.js': r'"id":\s*"((?:ticket)_(\d+)_(\d+))"',
    'junction-situations.js': r'"id":\s*"((?:ticket)_(\d+)_(\d+))"',
    'road-situations.js': r'"id":\s*"((?:road)_(\d+)_(\d+))"',
}

ids = {}
for name, pattern in SOURCES.items():
    text = (GAME / name).read_text(encoding='utf-8')
    for sid, t, q in re.findall(pattern, text):
        ids.setdefault(sid, (int(t), int(q)))

def game_json(name, prefix):
    text = (GAME / name).read_text(encoding='utf-8')
    body = text.split(prefix, 1)[1]
    return json.loads(body[:body.rindex(';')] if name != 'junction-situations.js' else body.split(';\nObject.assign', 1)[0])

# Russian copies in the game must equal the Russian question they name.
ru_copies = {s['id']: s for s in game_json('road-situations.js', 'window.PDD_ROAD_SITUATIONS = ')}
ru_copies.update({s['id']: s for s in game_json('junction-situations.js', 'window.PDD_EXTRA_SITUATIONS = ')})
for sid, copy in ru_copies.items():
    t, q = ids[sid]
    qq = question('ru', t, q)
    assert copy['title'] == qq['question'], (sid, 'title')
    assert copy['explanation'] == qq['comment'], (sid, 'explanation')
    assert copy['options'] == [a['text'] for a in qq['answers']], (sid, 'options')

table = {}
for sid, (t, q) in sorted(ids.items(), key=lambda kv: (kv[1], kv[0])):
    ru = question('ru', t, q)
    entry = {}
    for lang in LANGS:
        src = question(lang, t, q)
        # The translation must keep the same answer order and the same correct index.
        assert [a['correct'] for a in src['answers']] == [a['correct'] for a in ru['answers']], (sid, lang)
        rule = rule_number(src['comment'])
        entry[lang] = {
            'ticket': (f'{t}-билет · {q}-сұрақ' if lang == 'kk' else f'Ticket {t} · Question {q}'),
            'title': src['question'],
            'options': [a['text'] for a in src['answers']],
            'explanation': src['comment'],
            'pddRule': RULE_TEXT[lang](rule) if rule else '',
        }
    table[sid] = entry

out = GAME / 'i18n-situations.js'
out.write_text(
    '// Situation texts in kk and en. Generated by tools/game_content/build_game_i18n.py from\n'
    '// questions_ab_<lang>.json; do not edit by hand. The Russian source stays in the game files.\n'
    'window.PDD_SITUATION_I18N = '
    + json.dumps(table, ensure_ascii=False, indent=1) + ';\n',
    encoding='utf-8',
)
print(len(table), 'situations ->', out)
