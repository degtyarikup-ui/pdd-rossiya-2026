#!/usr/bin/env python3
"""Добавляет народные (разговорные) названия знаков в signs.json (Россия).

Народное название — то, как знак называют в живой речи водители и инструкторы:
«кирпич», «лежачий полицейский». В приложении оно показывается ОТДЕЛЬНО от
официального и явно помечено как народное — чтобы человек, который слышал
только разговорное имя, нашёл знак, но на экзамене назвал его правильно.

Список намеренно короткий. Сюда попадает только то, что действительно
в широком обиходе; выдуманные «народные» названия хуже, чем их отсутствие —
человек выучит слово, которого никто не употребляет. Расширять список стоит
по реальным запросам пользователей, а не по догадкам.

Запуск:  python3 tools/ru_content/add_folk_names.py
Идемпотентен: повторный запуск ничего не ломает.
"""

import json
import pathlib
import sys

SIGNS = pathlib.Path("assets/countries/ru/questions/signs.json")

# номер знака → народное название
FOLK_NAMES = {
    # Абсолютная классика: знает даже человек без прав.
    "3.1": "кирпич",
    "1.17": "лежачий полицейский",
    # Белый круг в красной кайме — «бублик» из-за формы.
    "3.2": "бублик",
    # Перекрёсток с круговым движением у всех «кольцо».
    "4.3": "кольцо",
    # Силуэт рабочего с лопатой на предупреждающем знаке.
    "1.25": "мужик с лопатой",
    # Разметку 1.14.1 зовут зеброй, и название перешло на знак перехода.
    "5.19.1": "зебра",
    "5.19.2": "зебра",
    # Красный круг, перечёркнутый косым крестом.
    "3.27": "крест",
    # Шевроны на повороте — «ёлочка».
    "1.34.1": "ёлочка",
    "1.34.2": "ёлочка",
}


def main() -> int:
    if not SIGNS.exists():
        print(f"нет файла {SIGNS} — запускать из корня репозитория", file=sys.stderr)
        return 1

    data = json.loads(SIGNS.read_text(encoding="utf-8"))

    applied, missing = 0, []
    for number, folk in FOLK_NAMES.items():
        found = False
        for signs in data.values():
            sign = signs.get(number)
            if sign is not None:
                sign["folkName"] = folk
                applied += 1
                found = True
                break
        if not found:
            missing.append(number)

    if missing:
        # Номер знака мог измениться в источнике — молча потерять название
        # хуже, чем упасть: пропажу никто не заметит.
        print(f"знаки не найдены в signs.json: {', '.join(missing)}", file=sys.stderr)
        return 1

    SIGNS.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"народных названий проставлено: {applied}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
