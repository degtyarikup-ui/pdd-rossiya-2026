def load_signs():
    return json.load(open(os.path.join(QDIR, 'signs.json'), encoding='utf-8'))


def build_sign_questions(signs):
    qs = []
    os.makedirs(IMG_QDIR, exist_ok=True)
    for group, numbers in SIGN_PICKS.items():
        group_signs = signs.get(group, {})
        titles = [v['title'] for v in group_signs.values()]
        for num in numbers:
            sign = group_signs.get(num)
            if not sign:
                continue
            correct = sign['title']
            distractors = [t for t in titles if t != correct]
            random.shuffle(distractors)
            answers = [(correct, True)] + [(d, False) for d in distractors[:2]]
            random.shuffle(answers)

            src = os.path.join(IMG_SIGNS, os.path.basename(sign['image']))
            img_name = 'sign_' + num.replace('.', '_')
            # PNG-байты с расширением .jpg: Flutter декодирует по содержимому,
            # а загрузчик вопросов добавляет «.jpg» к имени.
            shutil.copyfile(src, os.path.join(IMG_QDIR, img_name + '.jpg'))

            qs.append({
                'id': f'by_sign_{num.replace(".", "_")}',
                'question': 'Что означает этот дорожный знак?',
                'answers': [{'text': t, 'correct': c} for t, c in answers],
                'comment': f'Знак {num} «{correct}» ({group.lower()}). Приложение 2 к ПДД Республики Беларусь.',
                'pddPoints': [],
                'image': img_name,
                'topic': ['Дорожные знаки'],
            })
    return qs


def build_text_questions():
    qs = []
    for i, (q, answers, comment, topic) in enumerate(TEXT_QUESTIONS):
        qs.append({
            'id': f'by_text_{i+1:03d}',
            'question': q,
            'answers': [{'text': t, 'correct': c} for t, c in answers],
            'comment': comment,
            'pddPoints': [],
            'image': None,
            'topic': [topic],
        })
    return qs


def main():
    signs = load_signs()
    sign_qs = build_sign_questions(signs)
    text_qs = build_text_questions()
    print(f'sign questions: {len(sign_qs)}, text questions: {len(text_qs)}')

    all_qs = sign_qs + text_qs
    random.shuffle(all_qs)

    per = 10
    n_tickets = len(all_qs) // per
    tickets = []
    for t in range(n_tickets):
        tickets.append({
            'number': t + 1,
            'questions': all_qs[t*per:(t+1)*per],
        })
    json.dump({'tickets': tickets},
              open(os.path.join(QDIR, 'questions_ab.json'), 'w', encoding='utf-8'),
              ensure_ascii=False, indent=1)

    topics = {}
    for q in all_qs:
        topics.setdefault(q['topic'][0], []).append(q)
    topics_out = {'topics': [
        {'name': k, 'questions': v} for k, v in sorted(topics.items())
    ]}
    json.dump(topics_out,
              open(os.path.join(QDIR, 'topics_ab.json'), 'w', encoding='utf-8'),
              ensure_ascii=False, indent=1)

    print(f'tickets: {n_tickets} × {per} = {n_tickets*per} questions used '
          f'(of {len(all_qs)} total)')
    print('topics:', {k: len(v) for k, v in topics.items()})


if __name__ == '__main__':
    main()
