const vm = require('node:vm');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const code = fs.readFileSync('assets/game/browser-bridge.js', 'utf8');
const handlers = {}, messages = [], parent = {postMessage: (data, origin) => messages.push({data:JSON.parse(data), origin})};
const window = {addEventListener: (type, callback) => handlers[type] = callback};
const context = {window, parent, location:{search:'?flutterWeb=1',origin:'https://app.test'},URLSearchParams};
vm.createContext(context);vm.runInContext(code,context);
window.FlutterChannel.postMessage('{"event":"ready"}');
assert.equal(messages[0].data.payload,'{"event":"ready"}');
handlers.message({source:{},origin:'https://app.test',data:JSON.stringify({bridge:'pdd-game',id:1,code:'window.leaked=true'})});
assert.equal(window.leaked,undefined);
handlers.message({source:parent,origin:'https://other.test',data:JSON.stringify({bridge:'pdd-game',id:1,code:'window.leaked=true'})});
assert.equal(window.leaked,undefined);
handlers.message({source:parent,origin:'https://app.test',data:JSON.stringify({bridge:'pdd-game',id:2,code:'2+3'})});
assert.equal(messages.at(-1).data.value,5);
let prevented=false;
handlers.keydown({code:'ArrowUp',repeat:false,preventDefault:()=>prevented=true});
assert.equal(prevented,true);assert.equal(messages.at(-1).data.down,true);
handlers.keyup({code:'ArrowUp',preventDefault:()=>{}});assert.equal(messages.at(-1).data.down,false);
const count=messages.length;
handlers.keydown({code:'KeyW',ctrlKey:true});assert.equal(messages.length,count);
handlers.blur();assert.equal(messages.at(-1).data.type,'blur');
console.log('Browser bridge: source/origin validation, results, keyboard, blur passed');
