#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Общие утилиты для парсинга официальных PDF вопросов MUP (латиница-конверсия).

Сербская кириллица → латиница: официальная биективная транслитерация
(укључујући диграфе љ→lj, њ→nj, џ→dž).
"""
import re

# Порядок важен: сначала диграфы (заглавные и «титульные»), потом одиночные.
_CYR2LAT = [
    ("Љ", "Lj"), ("Њ", "Nj"), ("Џ", "Dž"),
    ("љ", "lj"), ("њ", "nj"), ("џ", "dž"),
    ("А", "A"), ("Б", "B"), ("В", "V"), ("Г", "G"), ("Д", "D"),
    ("Ђ", "Đ"), ("Е", "E"), ("Ж", "Ž"), ("З", "Z"), ("И", "I"),
    ("Ј", "J"), ("К", "K"), ("Л", "L"), ("М", "M"), ("Н", "N"),
    ("О", "O"), ("П", "P"), ("Р", "R"), ("С", "S"), ("Т", "T"),
    ("Ћ", "Ć"), ("У", "U"), ("Ф", "F"), ("Х", "H"), ("Ц", "C"),
    ("Ч", "Č"), ("Ш", "Š"),
    ("а", "a"), ("б", "b"), ("в", "v"), ("г", "g"), ("д", "d"),
    ("ђ", "đ"), ("е", "e"), ("ж", "ž"), ("з", "z"), ("и", "i"),
    ("ј", "j"), ("к", "k"), ("л", "l"), ("м", "m"), ("н", "n"),
    ("о", "o"), ("п", "p"), ("р", "r"), ("с", "s"), ("т", "t"),
    ("ћ", "ć"), ("у", "u"), ("ф", "f"), ("х", "h"), ("ц", "c"),
    ("ч", "č"), ("ш", "š"),
]


def to_latin(s):
    for cyr, lat in _CYR2LAT:
        s = s.replace(cyr, lat)
    return s


# Маркеры вариантов ответа (кириллица): а) б) в) г) д) е) ж) з)
OPTION_LETTERS = "абвгдежзиј"


def clean_ws(s):
    return " ".join(s.split()).strip()


# Колонтитул/копирайт MUP — ТОЛЬКО точные фразы бланка (не обычные сербские
# слова вроде «posla/poslova» — те ложно совпадали с грубым "POSLOVA").
_FOOTER_RE = re.compile(
    r"REPUBLIKA SRBIJA|MINISTARSTVO UNUTRA[SŠ]NJIH POSLOVA|"
    r"UPRAVA SAOBRA[CĆ]AJNE POLICIJE|"
    r"zabranjeno je kori[sš][cć]enje|u komercijalne svrhe|"
    r"bilo kojim sredstvima",
    re.IGNORECASE,
)


def is_garbled(question_text, options):
    """ТОЛЬКО структурный брак парсинга — не смысловой.

    Сербский текст легитимно содержит однобуквенные токены (предлоги u/i/a/o,
    категории «A,», «B,», числа-ссылки на рисунок), поэтому эвристика
    по длине токенов исключена — она давала ложные срабатывания на
    полностью корректных вопросах. Смысловая проверка «связный ли текст»
    делается агентом на этапе определения/верификации ответа (у него есть
    понимание языка, у regex — нет).
    """
    full = question_text + " " + " ".join(options)
    if _FOOTER_RE.search(full):
        return True
    if not question_text.strip():
        return True
    if len(options) < 2:
        return True
    if any(not o.strip() for o in options):
        return True
    return False
