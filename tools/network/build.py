#!/usr/bin/env python3
"""Road network -> surfaces Godot draws (game_godot/network/build/<id>.json).

    tools/network/.venv/bin/python tools/network/build.py [id ...]

The build is derived data: the network JSON is the source, this file is
regenerated by the editor on every save and by this script on demand (it is
git-ignored). Surfaces are constrained triangulations (the `triangle` library),
so the drawn asphalt is exactly the area the car may drive on:
- asphalt  : road polygons minus the islands (holes), at road level;
- island   : the islands, raised to kerb height;
- pavement : the ring around the roads (offset by the pavement width), raised;
- kerbs    : vertical walls on every edge between road and raised ground.
Markings and signs are not built here yet (see docs/game/road-network.md).
"""
import json
import sys
from pathlib import Path

import numpy as np
import triangle
from shapely.geometry import Polygon
from shapely.ops import unary_union

ROOT = Path(__file__).resolve().parents[2]
NET = ROOT / "game_godot" / "network"
BUILD = NET / "build"

SIDEWALK = 3.2       # pavement width beside the carriageway (m)
KERB = 0.18          # height of kerbs and pavement (m)
ROAD_Y = 0.0         # carriageway level (m); the same as the street's (scripts/street.gd ROAD_LEVEL)
ASPHALT = "#2c2f36"
PAVEMENT = "#747970"
KERB_COLOUR = "#b9b4ab"


def crop_box(scene: dict) -> Polygon:
    """The square the junction is drawn in: beyond it the game's own street goes on (street.gd)."""
    c = float(scene.get("crop", 90.0))
    return Polygon([(-c, -c), (c, -c), (c, c), (-c, c)])


def road_geometry(scene: dict):
    """(road without islands, islands) as shapely geometry, inside the crop square."""
    filled, holes = [], []
    for r in scene.get("roads", []):
        filled.append(Polygon(r["outer"]).buffer(0))
        for h in r.get("holes", []):
            holes.append(Polygon(h).buffer(0))
    box = crop_box(scene)
    road = (unary_union(filled) if filled else Polygon()).intersection(box)
    islands = unary_union(holes).intersection(road) if holes else Polygon()
    return road.difference(islands), islands


def triangulate(geom):
    """Constrained triangulation of polygons with holes -> (flat xz list, index list)."""
    verts, segs, holes = [], [], []
    parts = list(geom.geoms) if hasattr(geom, "geoms") else [geom]
    for p in parts:
        if p.is_empty or p.geom_type != "Polygon" or p.area < 1e-4:
            continue
        for ring in [p.exterior, *p.interiors]:
            coords = list(ring.coords)[:-1]
            base = len(verts)
            verts.extend(coords)
            n = len(coords)
            segs.extend((base + i, base + (i + 1) % n) for i in range(n))
        for ring in p.interiors:
            holes.append(Polygon(ring).representative_point().coords[0])
    if not verts:
        return [], []
    spec = {"vertices": np.array(verts, dtype=float), "segments": np.array(segs, dtype=int)}
    if holes:
        spec["holes"] = np.array(holes, dtype=float)
    result = triangle.triangulate(spec, "p")
    flat = np.round(result["vertices"], 3).ravel().tolist()
    return flat, result["triangles"].ravel().tolist()


def on_crop_edge(a, b, c: float, tol: float = 1e-3) -> bool:
    """Both ends lie on the same side of the crop square: the cut through the road, not a kerb."""
    for axis in (0, 1):
        for side in (-c, c):
            if abs(a[axis] - side) < tol and abs(b[axis] - side) < tol:
                return True
    return False


def walls(geom, crop: float = 90.0):
    """Flat [x0, z0, x1, z1, ...] pairs for every kerb edge of the road (not the cut at the crop edge)."""
    out = []
    parts = list(geom.geoms) if hasattr(geom, "geoms") else [geom]
    for p in parts:
        if p.is_empty or p.geom_type != "Polygon":
            continue
        for ring in [p.exterior, *p.interiors]:
            c = list(ring.coords)
            for a, b in zip(c[:-1], c[1:]):
                if on_crop_edge(a, b, crop):
                    continue
                out.extend([round(a[0], 3), round(a[1], 3), round(b[0], 3), round(b[1], 3)])
    return out


def build(scene: dict) -> dict:
    road, islands = road_geometry(scene)
    # The pavement ring is cut at the crop square too: past it the street's own pavement goes on,
    # and a ring that ran on would stand across the carriageway there.
    pavement = unary_union(
        [Polygon(r["outer"]).buffer(0) for r in scene.get("roads", [])]
    ).buffer(SIDEWALK, quad_segs=8).difference(road.union(islands)).intersection(crop_box(scene))
    v, t = triangulate(road)
    asphalt = {"id": "asphalt", "y": ROAD_Y, "layer": "asphalt", "colour": ASPHALT, "verts": v, "idx": t}
    v, t = triangulate(islands)
    island = {"id": "island", "y": KERB, "layer": "pavement", "colour": PAVEMENT, "verts": v, "idx": t}
    v, t = triangulate(pavement)
    pave = {"id": "pavement", "y": KERB, "layer": "pavement", "colour": PAVEMENT, "verts": v, "idx": t}
    return {
        "id": scene["id"],
        "surfaces": [asphalt, island, pave],
        "kerbs": {"y0": ROAD_Y, "y1": KERB, "colour": KERB_COLOUR, "segs": walls(road, float(scene.get("crop", 90.0)))},
    }


def main(argv):
    BUILD.mkdir(parents=True, exist_ok=True)
    ids = argv or sorted(p.stem for p in NET.glob("*.json"))
    for scene_id in ids:
        scene = json.loads((NET / f"{scene_id}.json").read_text(encoding="utf-8"))
        scene.setdefault("id", scene_id)
        out = build(scene)
        (BUILD / f"{scene_id}.json").write_text(json.dumps(out, separators=(",", ":")), encoding="utf-8")
        tris = sum(len(s["idx"]) // 3 for s in out["surfaces"])
        print(f"{scene_id:14} triangles {tris:6}  kerb walls {len(out['kerbs']['segs']) // 4}")


if __name__ == "__main__":
    main(sys.argv[1:])
