#!/usr/bin/env python3
"""Road network -> surfaces Godot draws (game_godot/network/build/<id>.json).

    tools/network/.venv/bin/python tools/network/build.py [id ...]

The build is derived data: the network JSON is the source, this file is
regenerated by the editor on every save and by this script on demand (it is
git-ignored). Surfaces are constrained triangulations (the `triangle` library),
so the drawn asphalt is exactly the area the car may drive on. Levels (metres):

    ROAD_Y    0.000  asphalt (carriageway), road minus islands
    LAWN_Y   -0.030  lawns and flower beds: 3 cm under the carriageway, 12 cm over the world's lawn
                     (world.gd, -0.15), 6 cm under the dirt overlay of the baked scene (0.031)
    MARK_Y    0.055  road markings, 5.5 cm over the asphalt
    KERB      0.180  islands and pavement; kerbs are walls from ROAD_Y up to KERB

The network draws the whole ground of the junction: asphalt, islands, pavement,
kerbs, lawns and markings. A lawn is cut out of the pavement and the roads; the
pavement is cut out of the lawn only where a lawn was drawn over it on purpose.
Surfaces that overlap in plan lie at least 3 cm apart (layers.py tests this); the
dirt overlay of the baked scene (textured, 3.1 cm over the asphalt) is the one
drawn surface the network does not own (layers.py reports it).

Lawns (`lawns`): polygons {id, outer, holes}; they are drawn at LAWN_Y and take the pavement's place
where they lie over it (never over the roads).
Markings (`markings`): each item is one of
    arrow    two axis `points` (tail -> forward), `direction` (straight, left, right,
             straight_left, straight_right, left_right, all), `width` (default 2.6 m);
    paint    polygons {outer, holes} as traced from the baked scene (migrate.py --layers);
    solid    polyline `points`, `width` (default 0.13);
    dashed   polyline `points`, `width`, dash 2 m with a 3 m gap (game.js corridorDashes);
    stop     bar from points[0] to points[1] across the lane, `width` (default 0.4);
             `stopStyle: "yield"` replaces the bar with separate yield triangles. Points run
             from the centre line toward the driver's right; tips face approaching traffic;
    zebra    points[0] -> points[1] is the crossing's centre line across the road: bars
             of `length` (default 4 m) along the traffic, 0.7 m wide, 0.7 m apart;
and the `colour` is "white" (default) or "yellow". Markings are drawn at MARK_Y, cut to the
carriageway with a 0.3 m margin (the baked paint reached a little past the edge).
Signs are not built here (they are baked props of the scene, see situation.gd).
Outlines: the roads, the islands and the lawns are tidied (closing and opening with a disc, TIDY_RADIUS
and LAWN_TIDY), so the traced edges do not jitter and the kerbs run smooth. The white edge lines are not
traced: they are the carriageway's outline offset EDGE_OFFSET inward, so they follow every rounding of
the kerb; the traced paint is cut back from the kerb (EDGE_BAND) to make room for them.
"""
