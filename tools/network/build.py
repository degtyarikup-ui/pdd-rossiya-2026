def crop_box(scene: dict) -> Polygon:
    """The square the junction is drawn in: beyond it the game's own street goes on (street.gd)."""
    c = float(scene.get("crop", 90.0))
    return Polygon([(-c, -c), (c, -c), (c, c), (-c, c)])


def polygon_of(item: dict):
    """A {outer, holes} item as a shapely polygon (repaired with buffer(0))."""
    holes = [Polygon(h).buffer(0) for h in item.get("holes", [])]
    poly = Polygon(item["outer"]).buffer(0)
    for h in holes:
        poly = poly.difference(h)
    return poly


# Soft rural ground, the same field as crossroads_junction.gd _ground_shares: every point near a
# dirt road gets its share of asphalt, dirt and grass by the distance to the paved and the unpaved
# carriageway, so the corners, the paved stretch and the grass shoulders cannot seam.
DIRT_BLEND = 1.5      # asphalt tone runs this far up a dirt road (m): the dirt reaches the asphalt
SHOULDER_EDGE = 0.6   # ... and this far onto dirt beside a paved road
GRASS_FADE = 1.1      # half-width of the dirt-to-grass blend
FIELD_EDGE = 0.2 + GRASS_FADE * 2.0   # the soft shoulder ends in pure grass this far out (m)
FIELD_STEP = 0.5      # grid of the blended mesh (m)
CURB_RADIUS = 5.0   # the inner corners of a junction get a curb radius (m), not a chamfer
TIDY_RADIUS = 0.6   # the outlines of roads and islands are closed and opened with this radius (m):
                    # the traced edges jitter by a few tenths of a metre, the kerbs must run smooth
EDGE_OFFSET = 0.25  # the white edge line's centre sits this far inside the kerb (m): where the traced edges are
EDGE_WIDTH = 0.15   # the traced edges lie 0.22-0.43 m from the kerb (measured on the junction scenes)
EDGE_BAND = 0.46    # traced paint closer than this to a kerb is cut back: zebra bars and stop lines end there
ALONG_KERB = 0.4    # a traced polygon with this share of its outline in the kerb band is an edge line: dropped


def polygons_json(geom) -> list:
    """A shapely (multi)polygon as [{outer, holes}] lists, for the game (RoadNetwork.carriageway)."""
    out = []
    for p in (geom.geoms if hasattr(geom, "geoms") else [geom]):
        if p.is_empty or p.geom_type != "Polygon":
            continue
        out.append({
            "outer": [[round(x, 3), round(y, 3)] for x, y in p.exterior.coords[:-1]],
            "holes": [[[round(x, 3), round(y, 3)] for x, y in ring.coords[:-1]] for ring in p.interiors],
        })
    return out


LAWN_TIDY = 2.0     # lawns and flower beds are wide shapes: their traced outlines wave by half a metre


def tidy(geom, radius: float = TIDY_RADIUS):
    """Closing then opening with a disc: small jitter of an outline goes, its large shape stays."""
    geom = geom.buffer(radius, quad_segs=16).buffer(-radius, quad_segs=16)
    geom = geom.buffer(-radius, quad_segs=16).buffer(radius, quad_segs=16)
    return geom.simplify(0.01)


TRACK_GAUGE = 1.524    # m between the rails (Russian tram gauge)
RAIL_WIDTH = 0.09      # m, a rail seen from above
TRACK_BED = 3.2        # m, the paved strip a track takes where it leaves the road (a depot entry)


def sample_tram_route(points: list) -> list:
    """Exactly Situation._smooth / Junction.Path, sampled at 0.4 m.

    Rails must follow the moving vehicle's curve, rather than the straight
    segments between editor handles. Only derived output is sampled.
    """
    if len(points) < 3:
        return [list(p) for p in points]
    out = []
    for i in range(len(points) - 1):
        p0, p1 = points[max(0, i - 1)], points[i]
        p2, p3 = points[i + 1], points[min(len(points) - 1, i + 2)]
        steps = max(1, math.ceil(math.dist(p1, p2) / 0.4))
        for s in range(steps):
            t = s / steps
            out.append([0.5 * (2 * p1[k] + (p2[k] - p0[k]) * t
                        + (2 * p0[k] - 5 * p1[k] + 4 * p2[k] - p3[k]) * t * t
                        + (3 * p1[k] - p0[k] - 3 * p2[k] + p3[k]) * t * t * t)
                        for k in (0, 1)])
    out.append(list(points[-1]))
    return out


def tram_track_lines(scene: dict) -> list:
    """Only rails used by this question's trams, with support behind their body.

    Retired rails remain in the author's source for undo/inspection but are not
    rendered. Authored routes, poses and road contours are never rewritten.
    """
    routes = {r["id"]: r for r in scene.get("routes", [])}
    tracks = {t["id"]: t for t in scene.get("tracks", [])}
    out = []
    for actor in scene.get("actors", []):
        if actor.get("type") != "tram":
            continue
        pts = routes.get(actor.get("route"), {}).get("points", [])
        sampled = sample_tram_route(pts)
        line = LineString(sampled) if len(sampled) >= 2 else None
        half_length = max(1.0, float(actor.get("halfLength", 5.0)))
        behind = half_length + 2.0
        track_pts = tracks.get(actor.get("track"), {}).get("points", [])
        if line is not None and line.length > 0.01:
            out.append(line)
            # The selected route contains the used branch; don't render any
            # other branches or the unused continuation of its former main line.
            if len(track_pts) >= 2:
                main = LineString(track_pts)
                pos = Point(actor["pos"])
                if main.distance(pos) < 3.5:
                    at = main.project(pos)
                    start = at + behind if actor.get("trackDir") == -1 else at - behind
                    prefix = substring(main, max(0.0, min(main.length, start)), at)
                    if isinstance(prefix, LineString) and prefix.length > 0.01:
                        out.append(prefix)
                        continue
            # Ordinary editor trams need no hand-drawn rails. Extend back only
            # enough to support the complete vehicle at its question position.
            start = sampled[0]
            forward = next((p for p in sampled[1:] if math.dist(start, p) > 0.01), None)
            if forward:
                distance = math.dist(start, forward)
                rear = [start[k] - (forward[k] - start[k]) / distance * behind for k in (0, 1)]
                out.append(LineString([rear, start]))
        else:
            # A stationary tram without a route still stands on rails. A missing
            # moving route is diagnosed by check.py, not invented by this builder.
            pos = actor["pos"]
            yaw = float(actor.get("yaw", 0.0))
            direction = [math.sin(yaw), math.cos(yaw)]
            out.append(LineString([[pos[k] - direction[k] * behind for k in (0, 1)],
                                   [pos[k] + direction[k] * behind for k in (0, 1)]]))
    return out


def track_lines(scene: dict) -> list:
    """Paved beds only for explicitly bound tracks used by a tram.

    Automatic route rails must not reshape the author's existing roads/kerbs.
    Runtime service entrances are planned separately around the saved scenery.
    """
    valid_tracks = {t["id"] for t in scene.get("tracks", []) if len(t.get("points", [])) >= 2}
    bound = [a for a in scene.get("actors", []) if a.get("type") == "tram" and a.get("track") in valid_tracks]
    if not bound:
        return []
    return tram_track_lines({**scene, "actors": bound})


def rails(scene: dict):
    """Two rails along each actual tram route, never along retired rail paint."""
    parts = []
    for line in tram_track_lines(scene):
        for side in (-1, 1):
            off = line.offset_curve(side * TRACK_GAUGE / 2)
            if not off.is_empty:
                parts.append(off.buffer(RAIL_WIDTH / 2, cap_style=2))
    return unary_union(parts) if parts else Polygon()


def authored_rails(scene: dict):
    """Explicitly visible tracks also exist without a tram; legacy routing guides stay hidden."""
    parts = []
    for track in scene.get("tracks", []):
        if track.get("render") is not True or track.get("railType") == "railway" or len(track.get("points", [])) < 2:
            continue
        line = LineString(sample_tram_route(track["points"]))
        if line.length < .01:
            continue
        for side in (-1, 1):
            offset = line.offset_curve(side * TRACK_GAUGE / 2)
            if not offset.is_empty:
                parts.append(offset.buffer(RAIL_WIDTH / 2, cap_style=2))
    return unary_union(parts) if parts else Polygon()


def road_geometry(scene: dict):
    """(road without islands, islands, all roads) as shapely geometry, inside the crop square.
    A tram track is paved too: where it leaves the road (into a depot) the kerb and the pavement
    open for it, the way a driveway does."""
    filled, holes = [], []
    for line in track_lines(scene):
        filled.append(line.buffer(TRACK_BED / 2, cap_style=2, join_style=1))
    for r in scene.get("roads", []):
        filled.append(Polygon(r["outer"]).buffer(0))
        for h in r.get("holes", []):
            holes.append(Polygon(h).buffer(0))
    box = crop_box(scene)
    roads = unary_union(filled) if filled else Polygon()
    # Closing: the concave corners of the outline (where two roads meet) get a rounded fillet.
    roads = roads.buffer(CURB_RADIUS, quad_segs=32).buffer(-CURB_RADIUS, quad_segs=32)
    # The crop square's edges are cuts, not kerbs: tidy rounds convex corners, so the band at the cut keeps
    # its square corners (the neighbouring scene meets the road there, see the stitching of the editor).
    cut_band = box.exterior.buffer(1.5, quad_segs=8)
    roads = tidy(roads).difference(cut_band).union(roads.intersection(cut_band)).intersection(box)
    # Layout streets already define their own end widths and curved centre lines.
    # Legacy square-end alignment would add a straight strip beside a curved sand road.
    if not (scene.get("layout") and any(r.get("surface") == "sand" for r in scene.get("roads", []))):
        roads = street_ends(roads, box)
    islands = tidy(unary_union(holes)).intersection(roads) if holes else Polygon()
    return roads.difference(islands), islands, roads


STREET_HALF = 4.2      # the game's street (street.gd ROAD_HALF): its carriageway meets the junction's
STREET_LEAD = 8.0      # metres of the street's exact profile kept inside the square at each street end


def street_ends(roads, box: Polygon):
    """Where the game's street goes on (a side's road about 8.4 m wide in its middle), the last metres
    of the junction are the street's own profile: the kerb, the edge line and the pavement meet the
    street without a step (the traced roads are 8.25 m and wander by a few centimetres)."""
    c = box.bounds[2]
    out = roads
    for side in ("n", "s", "e", "w"):
        if side in ("n", "s"):
            z = c - 0.05 if side == "n" else -c + 0.05
            cut = roads.intersection(LineString([(-c, z), (c, z)]))
        else:
            x = c - 0.05 if side == "e" else -c + 0.05
            cut = roads.intersection(LineString([(x, -c), (x, c)]))
        if cut.is_empty:
            continue
        b = cut.bounds
        lo, hi = (b[0], b[2]) if side in ("n", "s") else (b[1], b[3])
        if abs((lo + hi) / 2) > 0.4 or not 7.6 < hi - lo < 9.2:
            continue
        h, a, e = STREET_HALF, c - STREET_LEAD, c + 1.0
        def strip(w):
            return {"n": Polygon([(-w, a), (w, a), (w, e), (-w, e)]), "s": Polygon([(-w, -e), (w, -e), (w, -a), (-w, -a)]),
                    "e": Polygon([(a, -w), (e, -w), (e, w), (a, w)]), "w": Polygon([(-e, -w), (-a, -w), (-a, w), (-e, w)])}[side]
        # Inside the strip the road is exactly the street; further in, the junction's own outline goes on.
        out = out.difference(strip(h + 0.6)).union(strip(h))
    return out.intersection(box)


def edge_lines(roads, box: Polygon):
    """The white edge lines: a band EDGE_WIDTH wide, EDGE_OFFSET inside every kerb of the roads
    (the outer kerb and the islands alike). Offset from the outline itself, so the line follows every
    rounding of the kerb exactly. The cut at the crop square is no kerb and gets no line."""
    inner = roads.buffer(-(EDGE_OFFSET - EDGE_WIDTH / 2), quad_segs=32)
    outer = roads.buffer(-(EDGE_OFFSET + EDGE_WIDTH / 2), quad_segs=32)
    band = inner.difference(outer)
    return band.difference(box.exterior.buffer(1.0))


def disabled_edge_mask(scene: dict, roads_all):
    """Arm edges and the roundabout's two contours have independent switches."""
    roads = scene.get("roads", [])
    disabled = unary_union([polygon_of(r) for r in roads if r.get("edge") is False])
    # Include rounded joins between disabled arms, just like the carriageway.
    mask = disabled.buffer(CURB_RADIUS, quad_segs=32).buffer(-CURB_RADIUS, quad_segs=32).buffer(0.6)
    # Arm rectangles reach into the island. They must not interrupt its enabled line.
    rings = [r for r in roads if "innerEdge" in r or "outerEdge" in r]
    ring_holes = unary_union([Polygon(h).buffer(0) for r in rings for h in r.get("holes", [])])
    mask = mask.difference(ring_holes.buffer(0.6))
    for r in rings:
        holes = unary_union([Polygon(h).buffer(0) for h in r.get("holes", [])])
        if r.get("outerEdge") is False:
            # The area added by this ring includes its approach fillets. Comparing
            # actual smoothed roads avoids cutting enabled edges farther up an arm.
            other = road_geometry({**scene, "roads": [item for item in roads if item is not r]})[2]
            # Tidy/closing can shift an otherwise identical arm by micrometres;
            # ignore those slivers before expanding the suppression mask.
            added = roads_all.difference(other.buffer(0.01)).buffer(0.6)
            mask = mask.union(added.difference(ring_holes.buffer(0.6)))
        if r.get("innerEdge") is False:
            mask = mask.union(holes.buffer(0.6))
    return mask


def along_kerb(poly, kerb) -> float:
    """The share of a polygon's outline that lies in the kerb's band (its edge runs along the kerb)."""
    total = near = 0
    for ring in [poly.exterior, *poly.interiors]:
        length = ring.length
        if length <= 0:
            continue
        for t in np.linspace(0.0, 1.0, int(min(400, max(8, length * 2))), endpoint=False):
            total += 1
            near += ring.interpolate(t * length).distance(kerb) < EDGE_BAND + 0.05
    return near / total if total else 0.0


def paint_geometry(m: dict, roads):
    """Traced paint of one marking item, without the lines that run along a kerb: the edge lines are
    drawn from the kerb itself (edge_lines), so a traced copy beside them would be a double line."""
    kerb = roads.boundary
    parts = []
    for pl in m.get("polygons", []):
        p = polygon_of(pl)
        if p.is_empty or (along_kerb(p, kerb) > ALONG_KERB and p.area > 0):
            continue
        parts.append(p)
    return unary_union(parts) if parts else Polygon()


def without_kerb_paint(geom, roads):
    """Traced paint is cut back from the kerb (zebra bars and stop lines end at it)."""
    return geom.difference(roads.boundary.buffer(EDGE_BAND))


def triangulate(geom):
    """Constrained triangulation of polygons with holes -> (flat xz list, index list)."""
    verts, segs, holes = [], [], []
    parts = list(geom.geoms) if hasattr(geom, "geoms") else [geom]
    # Valid polygon components may touch at one vertex (e.g. a divider cap
    # clipped at the scene border). Triangle cannot accept duplicate PSLG
    # vertices from separate components and may crash the editor process.
    if len(parts) > 1:
        indices = []
        for part in parts:
            pv, pt = triangulate(part)
            base = len(verts) // 2
            verts.extend(pv)
            indices.extend(i + base for i in pt)
        return verts, indices
    for p in parts:
        if p.is_empty or p.geom_type != "Polygon" or p.area < 1e-4:
            continue
        for ring in [p.exterior, *p.interiors]:
            coords = list(ring.coords)[:-1]
            base = len(verts)
            verts.extend(coords)
            n = len(coords)
            segs.extend((base + i, base + (i + 1) % n) for i in range(n))
        for ring in p.interiors:
            holes.append(Polygon(ring).representative_point().coords[0])
    if not verts:
        return [], []
    spec = {"vertices": np.array(verts, dtype=float), "segments": np.array(segs, dtype=int)}
    if holes:
        spec["holes"] = np.array(holes, dtype=float)
    result = triangle.triangulate(spec, "p")
    tris = result["triangles"].copy()
    pts = result["vertices"]
    a, b, c = pts[tris[:, 0]], pts[tris[:, 1]], pts[tris[:, 2]]
    signed = (b[:, 0] - a[:, 0]) * (c[:, 1] - a[:, 1]) - (c[:, 0] - a[:, 0]) * (b[:, 1] - a[:, 1])
    # A clockwise triangle is culled as its back side: the game would show a hole. Wind them all the same way.
    tris[signed < 0] = tris[signed < 0][:, [0, 2, 1]]
    flat = np.round(pts, 3).ravel().tolist()
    return flat, tris.ravel().tolist()


def on_crop_edge(a, b, c: float, tol: float = 1e-3) -> bool:
    """Both ends lie on the same side of the crop square: the cut through the road, not a kerb."""
    for axis in (0, 1):
        for side in (-c, c):
            if abs(a[axis] - side) < tol and abs(b[axis] - side) < tol:
                return True
    return False


def walls(geom, crop: float = 90.0):
    """Flat [x0, z0, x1, z1, ...] pairs for every kerb edge of the road (not the cut at the crop edge)."""
    out = []
    parts = list(geom.geoms) if hasattr(geom, "geoms") else [geom]
    for p in parts:
        if p.is_empty or p.geom_type != "Polygon":
            continue
        for ring in [p.exterior, *p.interiors]:
            c = list(ring.coords)
            for a, b in zip(c[:-1], c[1:]):
                if on_crop_edge(a, b, crop):
                    continue
                out.extend([round(a[0], 3), round(a[1], 3), round(b[0], 3), round(b[1], 3)])
    return out


def marking_geometry(m: dict):
    """One marking item as shapely geometry (before the cut to the carriageway). A line may carry a
    second one beside it ("double": "solid" | "dashed", "side": 1 or -1, DOUBLE_GAP apart): a double
    solid line, or a solid and a broken one side by side (1.11)."""
    geom = single_marking(m)
    second = m.get("double")
    if second in ("solid", "dashed") and m.get("type") in ("solid", "dashed") and len(m.get("points", [])) >= 2:
        line = LineString([tuple(p) for p in m["points"]]).offset_curve(DOUBLE_GAP * float(m.get("side", 1)))
        if not line.is_empty and line.geom_type == "LineString":
            geom = unary_union([geom, single_marking({**m, "type": second, "points": list(line.coords)})])
    return geom


DOUBLE_GAP = 0.28    # centre to centre of the two lines of a double marking (m)


def single_marking(m: dict):
    kind = m.get("type", "solid")
    if kind == "bus_stop":
        return bus_stop_marking.geometry(m)
    if kind == "arrow":
        return direction_marking.geometry(m)
    if kind == "paint":
        parts = [polygon_of(p) for p in m.get("polygons", [])]
        return unary_union(parts) if parts else Polygon()
    pts = [tuple(p) for p in m.get("points", [])]
    if kind == "stop" and m.get("stopStyle") == "yield":
        if len(pts) < 2:
            return Polygon()
        (ax, az), (bx, bz) = pts[:2]
        dx, dz = bx - ax, bz - az
        length = math.hypot(dx, dz)
        if length < YIELD_BASE:
            return Polygon()
        ux, uz = dx / length, dz / length
        nx, nz = -uz, ux  # From centre line to the driver's right: tips point toward the driver.
        count = max(1, math.floor((length + YIELD_GAP + 1e-9) / (YIELD_BASE + YIELD_GAP)))
        inset = (length - (count * YIELD_BASE + (count - 1) * YIELD_GAP)) / 2
        triangles = []
        for i in range(count):
            at = inset + i * (YIELD_BASE + YIELD_GAP)
            triangles.append(Polygon([
                (ax + ux * at, az + uz * at),
                (ax + ux * (at + YIELD_BASE), az + uz * (at + YIELD_BASE)),
                (ax + ux * (at + YIELD_BASE / 2) + nx * YIELD_DEPTH,
                 az + uz * (at + YIELD_BASE / 2) + nz * YIELD_DEPTH),
            ]))
        return unary_union(triangles)
    if kind in ("solid", "stop"):
        if len(pts) < 2:
            return Polygon()
        w = float(m.get("width", MARK_WIDTH[kind]))
        return LineString(pts).buffer(w / 2, cap_style=2, join_style=2)
    if kind == "dashed":
        if len(pts) < 2:
            return Polygon()
        w = float(m.get("width", MARK_WIDTH["dashed"]))
        line = LineString(pts)
        dashes, at = [], 0.0
        while at < line.length:
            end = min(at + DASH, line.length)
            if end - at > 0.05:
                dashes.append(substring(line, at, end).buffer(w / 2, cap_style=2, join_style=2))
            at += DASH + GAP
        return unary_union(dashes) if dashes else Polygon()
    if kind == "zebra":
        if len(pts) < 2:
            return Polygon()
        (ax, az), (bx, bz) = pts[0], pts[1]
        dx, dz = bx - ax, bz - az
        length = float(np.hypot(dx, dz))
        if length < 1e-6:
            return Polygon()
        ux, uz = dx / length, dz / length          # across the road
        nx, nz = -uz, ux                           # along the traffic
        half = float(m.get("length", ZEBRA_LENGTH)) / 2
        bars, t = [], ZEBRA_STRIPE / 2
        while t <= length - ZEBRA_STRIPE / 2 + 1e-9:
            cx, cz = ax + ux * t, az + uz * t
            a = (cx - nx * half, cz - nz * half)
            b = (cx + nx * half, cz + nz * half)
            bars.append(LineString([a, b]).buffer(ZEBRA_STRIPE / 2, cap_style=2))
            t += 2 * ZEBRA_STRIPE
        return unary_union(bars) if bars else Polygon()
    raise ValueError(f"unknown marking type {kind!r}")


def ground(scene: dict):
    """What the network draws on the ground, before lawns: (carriageway, islands, all road outlines,
    the pavement ring), all inside the crop square. migrate.py cuts the same areas out of baked grass."""
    road, islands, roads_all = road_geometry(scene)
    box = crop_box(scene)
    # The pavement ring around the roads (offset by the pavement width), raised.
    # Grown from the tidied roads (roads_all), not the raw outlines: the pavement's edge is as smooth as the kerb.
    ring = roads_all.buffer(SIDEWALK, quad_segs=32).difference(road.union(islands)).intersection(box)   # 32: smooth corners, no steps
    return road, islands, roads_all, ring


def roadside_roads(scene, key):
    """Include junction fillers only when all adjoining arms share the roadside."""
    layout = scene.get("layout") or {}
    nodes = {f"road_{n['id']}": n['id'] for n in layout.get("nodes", [])}
    def enabled(r):
        return bool(r.get("shoulder")) if key == "shoulder" else r.get("walk") is not False
    roads = scene.get("roads", [])
    result = [r for r in roads if r.get("id") not in nodes and enabled(r)]
    for r in roads:
        if r.get("id") not in nodes: continue
        node = nodes[r['id']]
        arms = [st for st in layout.get("streets", []) if node in (st['a'], st['b'])]
        if arms and all(enabled(st) for st in arms): result.append(r)
    return result


def sidewalk_support(scene: dict):
    """The streets that have sidewalks own their full pavement corridor at a join.

    A disabled branch must not punch through the opposite sidewalk of a narrow
    through street. Node discs are junction filler, not independent sidewalks.
    Smoothing only the enabled roads keeps normal corners between enabled arms.
    """
    roads = scene.get("roads", [])
    if not any(r.get("walk") is False for r in roads):
        return None
    nodes = {f"road_{n['id']}" for n in (scene.get("layout") or {}).get("nodes", [])}
    enabled = roadside_roads(scene, "walk")
    if not enabled:
        return Polygon()
    supported = road_geometry({**scene, "roads": enabled, "actors": [], "tracks": []})[2]
    return supported.buffer(SIDEWALK, quad_segs=32)


def _smooth(e0, e1, x):
    t = min(1.0, max(0.0, (x - e0) / (e1 - e0)))
    return t * t * (3 - 2 * t)


def ground_shares(p: Point, paved, unpaved) -> tuple:
    """(asphalt, dirt, grass) at p, summing to 1 (crossroads_junction.gd _ground_shares)."""
    dp = paved.distance(p) if not paved.is_empty else math.inf
    du = unpaved.distance(p)
    reach = DIRT_BLEND + (SHOULDER_EDGE - DIRT_BLEND) * _smooth(0.0, 2.0, du)
    asphalt = 1.0 - _smooth(0.0, reach, dp) if dp < math.inf else 0.0
    grass = _smooth(0.2, FIELD_EDGE, du) * (1.0 - asphalt)
    return asphalt, 1.0 - asphalt - grass, grass


def soft_ground(sand, paved, solid, box):
    """The dirt road as surfaces: a blended grid where anything changes (DIRT_BLEND metres from the
    asphalt and the grass shoulder around it) and plain soil elsewhere. Returns (surfaces, the
    shoulder area taken from the lawn)."""
    shoulder = sand.buffer(FIELD_EDGE, quad_segs=16).difference(solid).intersection(box)
    near = sand.intersection(paved.buffer(DIRT_BLEND + 0.5)) if not paved.is_empty else Polygon()
    edge_band = sand.difference(sand.buffer(-0.6))
    region = unary_union([shoulder, near, edge_band]).intersection(box)
    plain = sand.difference(region)
    verts, idx, shares = [], [], []
    x0, z0, x1, z1 = region.bounds
    nx, nz = max(1, math.ceil((x1 - x0) / FIELD_STEP)), max(1, math.ceil((z1 - z0) / FIELD_STEP))
    from shapely.prepared import prep
    covered = prep(region)
    index = {}
    def vertex(x, z):
        key = (round(x, 4), round(z, 4))
        if key not in index:
            index[key] = len(verts) // 2
            verts.extend([round(x, 3), round(z, 3)])
            shares.extend(round(w, 3) for w in ground_shares(Point(x, z), paved, sand))
        return index[key]
    for iz in range(nz):
        for ix in range(nx):
            cell = Polygon([(x0 + ix * FIELD_STEP, z0 + iz * FIELD_STEP), (x0 + (ix + 1) * FIELD_STEP, z0 + iz * FIELD_STEP),
                            (x0 + (ix + 1) * FIELD_STEP, z0 + (iz + 1) * FIELD_STEP), (x0 + ix * FIELD_STEP, z0 + (iz + 1) * FIELD_STEP)])
            if not covered.intersects(cell):
                continue
            piece = cell if covered.contains(cell) else cell.intersection(region)
            for g in getattr(piece, "geoms", [piece]):
                if g.geom_type != "Polygon" or g.area < 1e-6:
                    continue
                v, t = triangulate(g)
                ids = [vertex(v[i * 2], v[i * 2 + 1]) for i in range(len(v) // 2)]
                idx.extend(ids[i] for i in t)
    out = [{"id": "dirt_field", "y": ROAD_Y, "layer": "field", "colour": "#6f5840", "verts": verts, "idx": idx, "shares": shares}]
    v, t = triangulate(plain)
    out.append({"id": "sand", "y": ROAD_Y, "layer": "sand", "colour": "#c2a570", "verts": v, "idx": t})
    return out, shoulder


def blended_shoulder(region, weights):
    """Closely spaced vertices interpolate continuous asphalt/earth/grass shares."""
    from shapely.prepared import prep
    covered = prep(region)
    verts, indices, shares, lookup = [], [], [], {}
    x0, z0, x1, z1 = region.bounds
    step = .4
    def vertex(x, z):
        key = (round(x, 3), round(z, 3))
        if key not in lookup:
            lookup[key] = len(verts) // 2
            verts.extend(key)
            shares.extend(weights(Point(*key)))
        return lookup[key]
    for ix in range(math.ceil((x1-x0)/step)):
        for iz in range(math.ceil((z1-z0)/step)):
            x, z = x0+ix*step, z0+iz*step
            cell = Polygon([(x,z),(x+step,z),(x+step,z+step),(x,z+step)])
            if not covered.intersects(cell): continue
            v, t = triangulate(cell if covered.contains(cell) else cell.intersection(region))
            ids = [vertex(v[i],v[i+1]) for i in range(0,len(v),2)]
            indices.extend(ids[i] for i in t)
    return {"id":"rural_shoulder", "y":ROAD_Y, "layer":"field", "soil_colour":"#96846b",
            "soil_kind":"gravel", "colour":"#96846b", "verts":verts, "idx":indices, "shares":shares}


def build(scene: dict) -> dict:
    road, islands, roads_all, ring = ground(scene)
    box = crop_box(scene)
    crop = float(scene.get("crop", 90.0))
    # Lawns win over the pavement: a flower bed drawn on the pavement stands on the lawn level.
    support = sidewalk_support(scene)
    lawn_polys, roadside_polys = [], []
    for item in scene.get("lawns", []):
        poly = polygon_of(item)
        # Generated roadside grass must yield to the adjoining street's sidewalk.
        # Hand-drawn lawns retain the author's explicit pavement cut-outs.
        if support is not None and item.get("auto") and str(item.get("id", "")).startswith("auto_lawn_"):
            roadside_polys.append(poly)
            continue
        lawn_polys.append(poly)
    # The lawns' outlines are traced too: they are tidied like the roads (the pavement is cut by them).
    lawn = tidy(unary_union(lawn_polys), LAWN_TIDY) if lawn_polys else Polygon()
    if roadside_polys:
        lawn = lawn.union(tidy(unary_union(roadside_polys), LAWN_TIDY).difference(support))
    lawn = lawn.intersection(box).difference(roads_all)
    # Use the road profile directly: smoothing a narrow lawn can restore the sidewalk.
    no_walk = ring.difference(support) if support is not None else Polygon()
    pavement = ring.difference(lawn).difference(no_walk)
    if support is not None:
        # Coincident rotated road/lawn edges can leave sub-millimetre slivers.
        # Resolve them at the same precision used by the exported vertex buffer.
        pavement = set_precision(pavement, .001)
    railway = railway_geometry.geometry(scene, road, pavement.union(islands), triangulate, sample_tram_route)
    if not railway["opening"].is_empty:
        pavement = pavement.difference(railway["opening"])
        islands = islands.difference(railway["opening"])
    no_edge = disabled_edge_mask(scene, roads_all)
    sand_raw = unary_union([polygon_of(r) for r in scene.get("roads", []) if r.get("surface") == "sand"])
    asphalt_raw = unary_union([polygon_of(r) for r in scene.get("roads", []) if r.get("surface") != "sand"]
                              + [line.buffer(TRACK_BED / 2, cap_style=2) for line in track_lines(scene)])
    # Give the smoothed shoulder the same material as its road. Only genuine asphalt
    # roads can create an asphalt transition; a contour adjustment must not create one.
    if not sand_raw.is_empty and scene.get("layout"):
        # As in crossroads: the rounded corners beside a dirt arm are dirt, not asphalt.
        # A junction's own outline (road_<node>) is no paved road there; its fillet
        # pieces that touch the dirt road go to the dirt, the rest stays asphalt.
        nodes = {f"road_{n.get('id')}" for n in scene["layout"].get("nodes", [])}
        junctions = [r for r in scene.get("roads", []) if r.get("id") in nodes and r.get("surface") != "sand"]
        if junctions:
            streets = unary_union([polygon_of(r) for r in scene.get("roads", [])
                                   if r.get("surface") != "sand" and r.get("id") not in nodes])
            corners = unary_union([polygon_of(r) for r in junctions]).difference(streets.buffer(0.05))
            parts = getattr(corners, "geoms", [corners])
            dirt_corners = unary_union([g for g in parts if not g.is_empty and g.intersects(sand_raw.buffer(0.5))])
            if not dirt_corners.is_empty:
                asphalt_raw = asphalt_raw.difference(dirt_corners.buffer(0.05))
                sand_raw = sand_raw.union(dirt_corners)
    sand = road.intersection(sand_raw.buffer(CURB_RADIUS + TIDY_RADIUS)).difference(asphalt_raw) if not sand_raw.is_empty else Polygon()
    # Hairline slivers where the smoothed road edge passes the asphalt outline are no dirt road:
    # their soft shoulder would show up across the paved road.
    sand = sand.buffer(-0.05).buffer(0.05).intersection(road) if not sand.is_empty else sand
    # Markings lie on the carriageway only; the island and the pavement are never painted over.
    marks = {}
    for m in scene.get("markings", []):
        colour = m.get("colour", "yellow" if m.get("type") == "bus_stop" else "white")
        if colour == "rail":
            continue  # Old traced rail paint is replaced by the actual tram routes.
        if colour not in MARK_COLOURS:
            raise ValueError(f"{scene.get('id')}: marking {m.get('id')} has unknown colour {colour!r}")
        if m.get("type", "solid") == "paint":
            geom = without_kerb_paint(paint_geometry(m, road), road)
        else:
            geom = marking_geometry(m)
            if m.get("type") == "bus_stop": geom = geom.intersection(road)
        marks.setdefault(colour, []).append(geom)
    # The edge lines follow the kerbs (also the roundabout's islands).
    marks.setdefault("white", []).append(edge_lines(road, box).difference(no_edge))

    v, t = triangulate(road.difference(sand))
    asphalt = {"id": "asphalt", "y": ROAD_Y, "layer": "asphalt", "colour": ASPHALT, "verts": v, "idx": t}
    # Dividing strips (a road item with "green": its islands are lawns, raised like the pavement).
    green = unary_union([Polygon(h).buffer(0) for r in scene.get("roads", []) if r.get("green") for h in r.get("holes", [])])
    green = green.intersection(islands) if not green.is_empty else Polygon()
    v, t = triangulate(islands.difference(green) if not green.is_empty else islands)
    island = {"id": "island", "y": KERB, "layer": "pavement", "colour": PAVEMENT, "verts": v, "idx": t}
    v, t = triangulate(green)
    median = {"id": "median", "y": KERB + 0.005, "layer": "grass", "colour": LAWN_COLOUR, "verts": v, "idx": t}
    v, t = triangulate(pavement)
    pave = {"id": "pavement", "y": KERB, "layer": "pavement", "colour": PAVEMENT, "verts": v, "idx": t}
    surfaces = [asphalt, island, median, pave] + railway["surfaces"]
    # A fixed-width shoulder, fading at its ends and across both lateral edges.
    shoulder_items = roadside_roads(scene, "shoulder")
    shoulder_roads = road_geometry({**scene, "roads": shoulder_items, "actors": [], "tracks": []})[2] if shoulder_items else Polygon()
    rural_shoulder = shoulder_roads.buffer(2.5, quad_segs=16).difference(roads_all.union(pavement).union(islands)).intersection(box)
    if not rural_shoulder.is_empty:
        # Only transitions to disabled arms are ends; rounded corners are continuous.
        disabled = unary_union([polygon_of(r) for r in scene.get("roads", [])
                                if r not in shoulder_items])
        ends = shoulder_roads.boundary.intersection(disabled.buffer(.06)).difference(roads_all.boundary.buffer(.1))
        def shoulder_shares(point):
            end_distance = box.boundary.distance(point)
            if not ends.is_empty:
                end_distance = min(end_distance, ends.distance(point))
            fade = _smooth(0, 7, end_distance)
            distance = roads_all.distance(point)
            width = 2.5 * fade
            earth = (1 - _smooth(max(0, width - .9), max(.001, width), distance)) * fade
            asphalt = (1 - _smooth(0, .5, distance)) * earth
            return (asphalt, earth - asphalt, 1 - earth)
        surfaces.append(blended_shoulder(rural_shoulder, shoulder_shares))
    visible_rails = authored_rails(scene).intersection(box)
    if not visible_rails.is_empty:
        v, t = triangulate(visible_rails)
        surfaces.append({"id": "authored_rails", "y": .047, "layer": "", "colour": "#929a9c", "verts": v, "idx": t})
    shoulder = Polygon()
    if not sand.is_empty:
        # Slivers left between the smoothed road and the dirt outline are not asphalt.
        paved = road.difference(sand).buffer(-0.05).buffer(0.05)
        field, shoulder = soft_ground(sand, paved, roads_all.union(pavement).union(islands).union(rural_shoulder), box)
        surfaces.extend(field)
    if scene.get("layout"):
        # A scene laid out from a road plan (the editor) has its own ground everywhere else: the baked
        # scene's old roads (where the plan has none now) are covered, and the game drops them (covers()).
        v, t = triangulate(box.difference(roads_all.union(pavement).union(shoulder)))
        surfaces.append({"id": "ground", "y": LAWN_Y, "layer": "grass", "colour": LAWN_COLOUR, "verts": v, "idx": t})
    if any(a.get("type") == "tram" for a in scene.get("actors", [])):
        marks.setdefault("rail", []).append(rails(scene))
    for colour in MARK_COLOURS:
        if colour not in marks:
            continue
        # The carriageway with a 0.3 m margin (the baked paint reached a little past the edge), islands cut out.
        geom = unary_union(marks[colour]).intersection(road.buffer(0.3).difference(islands))
        if not railway["bed"].is_empty:
            geom = geom.difference(railway["bed"])
        # Every separate piece (a dash, a zebra bar) is triangulated on its own: in one triangulation the
        # gaps between the pieces would be filled.
        v, t = [], []
        for piece in (geom.geoms if hasattr(geom, "geoms") else [geom]):
            pv, pt = triangulate(piece)
            base = len(v) // 2
            v.extend(pv)
            t.extend(i + base for i in pt)
        surfaces.append({"id": f"marking_{colour}", "y": MARK_Y, "layer": "", "colour": MARK_COLOURS[colour],
                         "verts": v, "idx": t})
    kerb_segments = walls(road, crop)
    kerb_segments = [v for i in range(0, len(kerb_segments), 4)
                     if pavement.buffer(0.04).union(islands.buffer(0.04)).intersects(LineString([(kerb_segments[i], kerb_segments[i+1]), (kerb_segments[i+2], kerb_segments[i+3])]))
                     for v in kerb_segments[i:i+4]]
    if not no_walk.is_empty and not pavement.is_empty:
        # Close the pavement ends with a kerb too; the old outer/road outlines already
        # have their own boundaries and must not be emitted a second time.
        original_edges = unary_union([Polygon(p["outer"], p["holes"]).boundary for p in polygons_json(ring)] + [road.boundary]).buffer(0.06)
        end_segments = walls(pavement, crop)
        kerb_segments.extend(v for i in range(0, len(end_segments), 4)
                             if not original_edges.covers(LineString([(end_segments[i], end_segments[i+1]), (end_segments[i+2], end_segments[i+3])]))
                             for v in end_segments[i:i+4])
    return {
        "id": scene["id"],
        "surfaces": surfaces,
        "kerbs": {"y0": ROAD_Y, "y1": KERB, "colour": KERB_COLOUR, "segs": railway_geometry.cut_kerbs(kerb_segments, railway["opening"])},
        # The drivable carriageway as the drawing has it (the car drives where the asphalt is).
        "carriageway": polygons_json(road),
    }


def main(argv):
    BUILD.mkdir(parents=True, exist_ok=True)
    ids = argv or sorted(p.stem for p in NET.glob("*.json"))
    for scene_id in ids:
        scene = json.loads((NET / f"{scene_id}.json").read_text(encoding="utf-8"))
        scene.setdefault("id", scene_id)
        out = build(scene)
        (BUILD / f"{scene_id}.json").write_text(json.dumps(out, separators=(",", ":")), encoding="utf-8")
        tris = sum(len(s["idx"]) // 3 for s in out["surfaces"])
        print(f"{scene_id:14} triangles {tris:6}  kerb walls {len(out['kerbs']['segs']) // 4}")


if __name__ == "__main__":
    main(sys.argv[1:])
