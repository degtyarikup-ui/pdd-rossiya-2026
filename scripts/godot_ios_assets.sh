#!/usr/bin/env bash
# Prepares the Godot game (game_godot/) for the Flutter iOS build (ios/Runner.xcodeproj):
#   ios/Godot/libgodot.ios.release.xcframework, ios/Godot/MoltenVK.xcframework — the engine
#                                 (Godot 4.7.2 export template, not in git)
#   ios/Godot/game.pck           — the exported game (not in git); the Runner copies it into
#                                 the app bundle (build phase «Copy Godot game pack»)
#   ios/Godot/engine.xcconfig    — link flags and the PDD_GODOT_ENGINE define, included by
#                                 ios/Flutter/{Debug,Release}.xcconfig
# Without them the Godot game is unavailable. Run after any change in game_godot/:
#   ./scripts/godot_ios_assets.sh
set -euo pipefail
cd "$(dirname "$0")/.."
command -v godot >/dev/null || { echo "Нет godot в PATH; см. docs/game/README.md"; exit 1; }
GODOT_VERSION="$(godot --version | sed -E 's/^([0-9]+\.[0-9]+(\.[0-9]+)?)\.([a-z]+)\..*/\1.\3/')"
[[ "$GODOT_VERSION" == 4.7.2.stable ]] || { echo "Нужен Godot 4.7.2 Standard, установлен $GODOT_VERSION"; exit 1; }
TEMPLATES="$HOME/Library/Application Support/Godot/export_templates/$GODOT_VERSION"
OUT=ios/Godot
[[ -f "$TEMPLATES/ios.zip" ]] || { echo "Нет шаблонов экспорта: $TEMPLATES/ios.zip"; exit 1; }
mkdir -p scratch output/godot
TMP="$(mktemp -d "$PWD/scratch/godot-ios.XXXXXX")"
trap 'rm -rf "$TMP"' EXIT
LOG="$PWD/output/godot/ios-export.log"
STAGE="$TMP/project"
PACKAGE="$TMP/package"
mkdir -p "$STAGE/tools/godot_export" "$STAGE/assets/audio" "$PACKAGE"
# Importers can rewrite tracked .import files. Work on a private copy so neither
# dirty source files nor concurrent author edits can be reset by this exporter.
rsync -a --exclude='.godot' --exclude='network/preview' --exclude='network/history' game_godot "$STAGE/"
cp tools/godot_export/export_{ui,question_images,question_audio}.py "$STAGE/tools/godot_export/"
ln -s "$PWD/assets/countries" "$STAGE/assets/countries"
ln -s "$PWD/assets/audio/feed" "$STAGE/assets/audio/feed"
# The shared MP3 cache belongs to Flutter. Validate it without pruning or
# rebuilding source assets while preparing this separate iOS engine package.
ln -s "$PWD/assets/audio/game_questions" "$STAGE/assets/audio/game_questions"
ln -s "$PWD/lib" "$STAGE/lib"
mkdir -p "$STAGE/assets/images"
ln -s "$PWD/assets/images/achievements" "$STAGE/assets/images/achievements"
python3 "$STAGE/tools/godot_export/export_ui.py"
python3 "$STAGE/tools/godot_export/export_question_images.py"
if ! python3 "$STAGE/tools/godot_export/export_question_audio.py" --check; then
  echo "Сначала обновите общие записи: python3 tools/godot_export/export_question_audio.py"; exit 1
fi
if ! godot --headless --path "$STAGE/game_godot" --import >"$LOG" 2>&1 || grep -Eq '^(SCRIPT ERROR:|ERROR:)' "$LOG"; then
  tail -60 "$LOG"; echo "Ошибка импорта Godot; полный журнал: $LOG"; exit 1
fi
if ! godot --headless --path "$STAGE/game_godot" --export-pack "iOS" "$PACKAGE/game.pck" >>"$LOG" 2>&1 || grep -Eq '^(SCRIPT ERROR:|ERROR:)' "$LOG"; then
  tail -60 "$LOG"; echo "Ошибка экспорта Godot; полный журнал: $LOG"; exit 1
fi
[[ -s "$PACKAGE/game.pck" ]] || { echo "Ошибка экспорта Godot: пакет игры пуст или отсутствует; журнал: $LOG"; exit 1; }
# Release slices only: the same engine serves Debug builds (no separate debug engine is needed).
unzip -oq "$TEMPLATES/ios.zip" 'libgodot.ios.release.xcframework/*' 'MoltenVK.xcframework/*' -d "$TMP"
mv "$TMP/libgodot.ios.release.xcframework" "$TMP/MoltenVK.xcframework" "$PACKAGE/"
# The template's SwiftUI demo app (defines _main) would clash with the Flutter app's main:
# the -ObjC link flag of CocoaPods pulls its object in. The embedding needs none of it.
# (The member list goes through a file: `ar -t | grep -q` exits early and, with pipefail, the
# check fails silently, so the object would stay in the library.)
LIB="$PACKAGE/libgodot.ios.release.xcframework/ios-arm64/libgodot.a"
ar -t "$LIB" > "$TMP/members.txt"
if grep -q '^app\.ios\.' "$TMP/members.txt"; then
  ar -d "$LIB" app.ios.template_release.arm64.o
  ranlib "$LIB"
fi
# The engine is linked for devices only: the template's simulator slice has no arm64
# objects, so simulator builds report the game unavailable.
cat > "$PACKAGE/engine.xcconfig" <<'XCCONFIG'
// Generated by scripts/godot_ios_assets.sh (not in git). Included by ios/Flutter/*.xcconfig.
GCC_PREPROCESSOR_DEFINITIONS[sdk=iphoneos*] = $(inherited) PDD_GODOT_ENGINE=1
LIBRARY_SEARCH_PATHS[sdk=iphoneos*] = $(inherited) "$(PROJECT_DIR)/Godot/libgodot.ios.release.xcframework/ios-arm64" "$(PROJECT_DIR)/Godot/MoltenVK.xcframework/ios-arm64"
OTHER_LDFLAGS[sdk=iphoneos*] = $(inherited) -lgodot -lMoltenVK
XCCONFIG
mkdir -p "$OUT"
rm -rf "$OUT/libgodot.ios.release.xcframework" "$OUT/MoltenVK.xcframework"
mv "$PACKAGE/libgodot.ios.release.xcframework" "$PACKAGE/MoltenVK.xcframework" "$OUT/"
cp "$PACKAGE/game.pck" "$PACKAGE/engine.xcconfig" "$OUT/"
echo "godot ios: $(du -h "$OUT/game.pck" | cut -f1) game, engine $(du -sh "$OUT/libgodot.ios.release.xcframework" | cut -f1)"
